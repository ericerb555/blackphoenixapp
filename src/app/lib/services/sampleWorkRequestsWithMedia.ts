/**
 * Initialize sample work requests in localStorage
 */
export function initializeSampleWorkRequests() {
  const existing = localStorage.getItem('work_requests');
  if (!existing) {
    localStorage.setItem('work_requests', JSON.stringify(sampleCompletedWorkRequests));
    console.log('✅ Initialized sample work requests with media for portfolio');
  } else {
    // Merge with existing
    const existingData = JSON.parse(existing);
    const merged = [...existingData];
    
    sampleCompletedWorkRequests.forEach(sample => {
      if (!merged.find(wr => wr.id === sample.id)) {
        merged.push(sample);
      }
    });
    
    localStorage.setItem('work_requests', JSON.stringify(merged));
    console.log('✅ Merged sample work requests with existing data');
  }
}
