/**
 * A snapshot of what is planned and how far through it we are.
 *
 * WHY THIS IS A BUILD STEP AND NOT A QUERY
 *
 * `tasks/*.md` is where this project records what it is building — 33 plans
 * with roughly a thousand checkboxes between them. Asked "what is unfinished",
 * the assistant could see errors, spend and agents, and nothing about the work
 * itself, because it runs in a Supabase edge function and has no filesystem
 * and no repository. The plans are in git; the assistant is not.
 *
 * So the counts are extracted here, at deploy time, into a module that ships
 * with the function. No route, no secret, no table — the digest describes the
 * repository and updates exactly when the repository is deployed, which is the
 * honest refresh rate for it.
 *
 * WHY GIT DATES MATTER MORE THAN THE COUNTS
 *
 * "495 open items" is noise. The signal is which plans are nearly finished,
 * which have stalled, and which were written and never started — and the only
 * thing separating a stalled plan from an active one is when it was last
 * touched. That comes from `git log`, so it is gathered here where git exists.
 *
 * The output IS committed, and the first attempt had it gitignored. The
 * pre-push hook refused that and was right: `taskDigest.ts` imports it, and an
 * import resolving only on a machine that has just run this script breaks a
 * fresh clone. The cost is a generated file in the path of every edit to a
 * task document, so expect conflicts here and resolve them by re-running this
 * script rather than merging the data by hand.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const TASKS = 'tasks';
const OUT = 'supabase/functions/server/taskDigest.generated.ts';

/** When a file was last committed, ISO, or null if git cannot say. */
function lastTouched(file) {
  try {
    const out = execFileSync('git', ['log', '-1', '--format=%cI', '--', file], {
      encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    return out || null;
  } catch {
    // A shallow clone or a file that has never been committed. Null reads as
    // "unknown age" downstream rather than as "touched today".
    return null;
  }
}

/**
 * The first heading, which is what the plan calls itself.
 *
 * Preferred over the filename because the filenames are slugs and the headings
 * are sentences somebody wrote on purpose.
 */
function title(body, fallback) {
  const m = body.match(/^#\s+(.+)$/m);
  return m ? m[1].trim().slice(0, 120) : fallback;
}

function build() {
  if (!fs.existsSync(TASKS)) {
    console.log('  no tasks/ directory — digest empty');
  }

  const plans = [];
  for (const name of fs.existsSync(TASKS) ? fs.readdirSync(TASKS) : []) {
    if (!name.endsWith('.md')) continue;
    const file = path.join(TASKS, name);
    if (!fs.statSync(file).isFile()) continue;

    const body = fs.readFileSync(file, 'utf8');
    // Indented boxes count: a nested checklist item is still an open item.
    const open = (body.match(/^[ \t]*- \[ \]/gm) || []).length;
    const done = (body.match(/^[ \t]*- \[[xX]\]/gm) || []).length;
    if (open === 0 && done === 0) continue;   // prose, not a checklist

    plans.push({
      file: name,
      title: title(body, name.replace(/\.md$/, '')),
      open, done,
      lastTouched: lastTouched(file),
    });
  }

  // Most unfinished work first, so a truncated read still sees what matters.
  plans.sort((a, b) => b.open - a.open);

  const generated = new Date().toISOString();
  const out = `/**
 * GENERATED by scripts/build-task-digest.mjs. Do not edit by hand.
 *
 * Committed, because taskDigest.ts imports it and a fresh clone has to
 * resolve that import — the pre-push hook refuses it otherwise, correctly.
 * A conflict here is expected whenever two branches touch tasks/: resolve it
 * by re-running \`npm run build:digest\`, never by merging the data by hand.
 *
 * Data only, with no imports on purpose. An \`import type\` here would sit
 * inside a template literal in the generator, where the pre-push hook reads it
 * as a real import from scripts/ and refuses the push. taskDigest.ts owns the
 * PlanSnapshot type and casts on load.
 */

export const GENERATED_AT = ${JSON.stringify(generated)};
export const PLANS = ${JSON.stringify(plans, null, 2)};
`;

  fs.writeFileSync(OUT, out);
  const totalOpen = plans.reduce((n, p) => n + p.open, 0);
  console.log(`  task digest: ${plans.length} plans, ${totalOpen} open items`);
}

build();
